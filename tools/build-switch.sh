app_shader_inputs() { # every app shader source and, transitively, the files it includes (sorted)
  local -A seen=()
  local queue=("$app_shader_dir"/*.hlsl "$app_shader_dir"/*.hlsli)
  local file include
  while [ "${#queue[@]}" -gt 0 ]; do
    file="$(realpath -m "${queue[0]}")"
    queue=("${queue[@]:1}")
    if [ -n "${seen[$file]:-}" ] || [ ! -f "$file" ]; then continue; fi
    seen[$file]=1
    while IFS= read -r include; do
      queue+=("$(dirname "$file")/$include")
    done < <(sed -n 's/^[[:space:]]*#[[:space:]]*include[[:space:]]*"\([^"]*\)".*/\1/p' "$file")
  done
  printf '%s\n' "${!seen[@]}" | sort
}
app_shader_id="$(
  echo "script=$(file_id tools/generate-switch-app-shaders.sh)"
  echo "dxc=$(find "$DXC_X64" -maxdepth 1 -type f -print0 | sort -z | xargs -0 sha256sum | cut -c1-64 | sha256sum | cut -c1-64)"
  while IFS= read -r input; do
    echo "${input#"$root_dir/"}=$(file_id "$input")"
  done < <(app_shader_inputs)
)"
app_shaders_present=true
while IFS= read -r app_shader; do
