  done
  bash tools/generate-switch-app-shaders.sh
  for header in "$app_shader_previous"/*.hlsl.spirv.h; do
    if [ -f "$header" ] && cmp -s "$header" "$app_shader_dir/${header##*/}"; then
      touch -r "$header" "$app_shader_dir/${header##*/}"
    fi
  done
  rm -rf "$app_shader_previous"
  printf '%s\n' "$app_shader_id" > "$app_shader_stamp"
fi

